def encode(rows):
    data=[]
    for row in rows:
        pixels=[int(x) for x in row]
        data.extend([sum((v & 1) << (7-i) for i,v in enumerate(pixels)),sum(((v>>1)&1)<<(7-i) for i,v in enumerate(pixels))])
    return data

